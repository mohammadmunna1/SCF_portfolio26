// Keywords → icon for supply chain wording (workflow steps, focus areas), checked in this order.
const KEYWORD_ICONS = [
  [/requisition|request/, LuClipboardList],
  [/approv/, LuBadgeCheck],
  [/purchase|procure|vendor|sourcing/, LuShoppingCart],
  [/supplier|deliver|logistic|transport|distribut|shipment/, LuTruck],
  [/report|analy|mis\b|data/, LuChartColumn],
  [/reconcil|compliance|audit/, LuClipboardCheck],
  [/fulfil|dispatch/, LuPackageCheck],
  [/stock|inventory|warehouse/, LuBoxes],
  [/order|invoice/, LuReceipt],
  [/demand|plan|forecast/, LuTarget],
  [/erp|sap|system|workflow/, LuWorkflow],
  [/ai\b|bot|automat/, LuBot],
  [/resolv|done|complete/, LuCircleCheck],
  [/query|message|chat|customer|conversation/, LuMessageSquare],
];

/** An icon for a short supply chain phrase ("Purchase order", "Stock reconciled") — a plain node otherwise. */
export function getKeywordIcon(text) {
  const value = String(text).toLowerCase();
  return KEYWORD_ICONS.find(([pattern]) => pattern.test(value))?.[1] || LuCircleDot;
}

